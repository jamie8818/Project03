const MISSION_EPOCH = Date.UTC(2026, 6, 19) / 86_400_000;

/** 同一天固定同一題；以首版車站題上線日為輪替起點。 */
export function missionForDate(today: string): DailyMission {
  const [year, month, day] = today.split('-').map(Number);
  const dateDay = Date.UTC(year, month - 1, day) / 86_400_000;
  const index = ((dateDay - MISSION_EPOCH) % MISSION_CATALOG.length + MISSION_CATALOG.length) % MISSION_CATALOG.length;
  return MISSION_CATALOG[index];
}
