type ChoiceSeed = readonly [label: string, meaning: string];

const card = (jp: string, kana: string, zh: string): MissionLessonCard => ({ jp, kana, zh });

const prep = (label: string, explain: string): MissionChoice => ({ label, explain });

function round(
  speaker: string,
  line: string,
  lineKana: string,
  audioOnly: boolean,
  prompt: string,
  choices: readonly ChoiceSeed[],
  correct: number,
  explain: string,
): MissionQuestion {
  return {
    speaker,
    line,
    lineKana,
    audioOnly,
    prompt,
    choices: choices.map(([label, meaning], index) => ({
      label,
      explain: index === correct ? explain : `${meaning}；${explain}`,
    })),
    correct,
    explain,
  };
}

function scenario(
  id: string,
  theme: string,
  title: string,
  jpTitle: string,
  request: string,
  shopLine: string,
  image: string,
  imageAlt: string,
  lesson: [MissionLessonCard, MissionLessonCard, MissionLessonCard],
  prepPrompt: string,
  prepChoices: [MissionChoice, MissionChoice, MissionChoice],
  questions: [MissionQuestion, MissionQuestion, MissionQuestion],
): DailyMission {
  return {
    id,
    theme,
    destinationLabel: theme,
    image,
    imageAlt,
    jpTitle,
    title,
    request,
    shopLine,
    lesson,
    phrase: lesson[0].jp,
    phraseKana: lesson[0].kana,
    phraseZh: lesson[0].zh,
    prepPrompt,
    prepChoices,
    questions,
    perfectLine: '三題一次通過。你把禮貌和本人一起帶到了。',
    retryLine: '任務完成。猜錯的句子現在也算認識了。',
  };
}

