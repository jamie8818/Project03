/** 依情境隨機抽一句 */
export function pickLine(context: keyof typeof LINES, rng: () => number = Math.random): string {
  const pool = LINES[context];
  return pool[Math.floor(rng() * pool.length)];
}

/** 依情境隨機抽一張圖 */
export function pickSprite(context: BuddyContext, rng: () => number = Math.random): string {
  const tags = CONTEXT_TAGS[context] as readonly string[];
  const pool = tags.length === 0 ? SPRITES : SPRITES.filter((s) => s.tags.some((t) => (tags as readonly string[]).includes(t)));
  const list = pool.length > 0 ? pool : SPRITES;
  return list[Math.floor(rng() * list.length)].f;
}

